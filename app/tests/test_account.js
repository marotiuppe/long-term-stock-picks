const BS = String.fromCharCode(92);
const assert = require('assert');
const { _t } = require('../modules/account/account.js');
assert.strictEqual(_t.usernameError(''), 'Enter a username.');
assert.ok(/at least 3/.test(_t.usernameError('ab')));
assert.ok(/at most 32/.test(_t.usernameError('a'.repeat(33))));
assert.strictEqual(_t.usernameError('a'.repeat(32)), '');
assert.ok(/letters, digits/.test(_t.usernameError('bad name')));
assert.ok(/letters, digits/.test(_t.usernameError('né_me')));
assert.strictEqual(_t.usernameError('Ab.c_d-9'), '');
assert.ok(/at least 10/.test(_t.passwordError('123456789', 'bob')));
assert.strictEqual(_t.passwordError('1234567890', 'bob'), '');
assert.ok(/at most 200/.test(_t.passwordError('x'.repeat(201), 'bob')));
assert.ok(/same as the username/.test(_t.passwordError('samename10x', 'samename10x')));
assert.deepStrictEqual(_t.passwordRules('short', 'bob'), { length: false, notUsername: true });
assert.deepStrictEqual(_t.passwordRules('', ''), { length: false, notUsername: false });
assert.strictEqual(_t.confirmError('a', 'a'), '');
assert.ok(_t.confirmError('a', 'b'));
['/portfolio.html', '/stock.html?symbol=TCS', '/a#b'].forEach(p => assert.strictEqual(_t.safeNext(p), p));
['//evil.com', '/'+BS+'evil.com', 'https://evil.com', 'javascript:alert(1)', '', null, undefined, 'portfolio.html', '/a\nb', '/\\x'].forEach(p => assert.strictEqual(_t.safeNext(p), ''));
let g = _t.viewModel(null);
assert.ok(g.guest && !g.signedIn && g.label === 'Guest');
assert.ok(_t.viewModel({ signedIn: false }).guest);
let u = _t.viewModel({ signedIn: true, username: 'sam', hasPassword: true, growwLinked: false, via: 'password', canSetPasswordFreely: false });
assert.ok(u.signedIn && u.label === 'sam' && u.hasPassword && !u.freePassword && u.via === 'password');
let w = _t.viewModel({ signedIn: true, username: null, hasPassword: false, growwLinked: true, via: 'groww', canSetPasswordFreely: true });
assert.ok(/no username yet/.test(w.label) && w.freePassword && w.growwLinked && w.via === 'groww');
assert.strictEqual(_t.viewModel({ signedIn: true, via: 'weird' }).via, null);
console.log('ok');
